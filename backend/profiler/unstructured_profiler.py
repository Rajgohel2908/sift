"""
profiler/unstructured_profiler.py — Quality profiling for PDF, DOCX, and image OCR output.

Computes basic text statistics and flags obvious quality problems.
"""

# Minimum word count before we warn that the document looks scanned / empty
SCANNED_PDF_WORD_THRESHOLD = 50


def profile_unstructured(parsed: dict, fmt: str) -> dict:
    """
    Profile text extracted from a PDF, DOCX, or image.

    Args:
        parsed: output dict from the relevant parser
        fmt:    "pdf" | "docx" | "image"

    Returns a dict with word_count, char_count, preview, issues, and
    format-specific extras (page_count, paragraph_count, confidence, modality).
    """
    issues = []

    # ── Pull the text out regardless of source format ─────────────────────────
    if fmt == "image":
        # Image parser returns text directly
        full_text  = parsed.get("text", "")
        modality   = parsed.get("modality", "ocr")
        confidence = parsed.get("confidence", 0.0)

        # Carry over any warnings generated by the image parser
        for w in parsed.get("warnings", []):
            issues.append({"message": w, "severity": "warning"})
    else:
        full_text = parsed.get("full_text", "")

    # ── Basic text stats ──────────────────────────────────────────────────────
    words      = full_text.split()
    word_count = len(words)
    char_count = len(full_text)
    preview    = full_text[:300]   # first 300 characters

    # ── Scanned-PDF / empty-doc warning ──────────────────────────────────────
    if fmt in ("pdf", "docx") and word_count < SCANNED_PDF_WORD_THRESHOLD:
        issues.append({
            "message": (
                f"Extracted only {word_count} words — document may be scanned, "
                "image-based, or largely empty. Text extraction may be incomplete."
            ),
            "severity": "warning",
        })

    # ── Assemble report ───────────────────────────────────────────────────────
    report: dict = {
        "word_count": word_count,
        "char_count": char_count,
        "preview":    preview,
        "issues":     issues,
    }

    # Format-specific extras
    if fmt == "pdf":
        report["page_count"] = parsed.get("page_count", 0)

    elif fmt == "docx":
        report["paragraph_count"] = parsed.get("paragraph_count", 0)

    elif fmt == "image":
        report["modality"]   = modality
        report["confidence"] = confidence

    return report
